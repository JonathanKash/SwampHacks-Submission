"""Generate benchmark/memes/README.md from manifest.resolved.json + download_log.json."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

INTRO = """# Lineage meme benchmark corpus

A local test corpus for **Lineage**, the image-provenance system that reconstructs the edit
family tree of a set of images (which file is the original, which copies derive from which,
and what edit produced each copy). Internet memes are a natural benchmark: each family has a
well-documented root image and thousands of public derivatives (captions, crops, re-uploads,
re-encodes, screenshots, cut-outs) whose ancestry is known.

**Nothing in `images/` is redistributed.** See *Licensing* below.

## Layout

| Path | What it is |
|---|---|
| `manifest.json` | Hand-curated + harvested manifest: per family, the root image (`original`) with its documented source, and 6-15 `variants` with a `kind` and a note. Generated by `tools/build_manifest.py` from `tools/sources.json` (curated provenance) and `tools/harvested.json` (URL pool). |
| `download.py` | Idempotent downloader (requests, browser-like User-Agent, 20 s timeout). Skips files already on disk, records failures, verifies every file opens with Pillow, and writes width/height/bytes/sha256 into `manifest.resolved.json`. |
| `manifest.resolved.json` | `manifest.json` + per-file metadata and per-family `stats` after a download run. **This is the file a benchmark harness should read.** |
| `download_log.json` | Per-URL status of the last run, with a `failures` list. |
| `images/<family>/` | Downloaded files (git-ignored). `original.*`, `vNN_<kind>.*`, optional `componentN.*` and `relatedN.*`. |
| `tools/` | `harvest.py` (scrapes Imgflip / Know Your Meme / Wikipedia for candidate URLs and origin text), `sources.json` (curated provenance, exclusions, composite components), `build_manifest.py`, `contact_sheet.py` (visual QA sheets), `write_readme.py`. |

## Manifest schema

```jsonc
{ "families": [ {
    "id": "distracted-boyfriend", "name": "...", "kym_url": "...",
    "original": { "file": "distracted-boyfriend/original.jpg", "url": "...", "source_url": "...",
                  "source_note": "...", "date": "2015-11-02", "is_true_source_photo": true,
                  /* after download: */ "width": 0, "height": 0, "bytes": 0, "sha256": "...", "format": "JPEG" },
    "variants": [ { "file": "...", "url": "...", "kind": "caption|crop|screenshot|mirror|color|sticker|lowres|other",
                    "note": "...", "origin": "imgflip template|kym icon|kym photo|imgflip meme|wikipedia|...",
                    "parent": "<file of the variant this one was derived from, when it is a 2nd-generation copy>" } ],
    "components":          [ /* only for composite roots: the source photos that were combined */ ],
    "related_not_derived": [ /* hard negatives: same subject / same photo shoot, NOT derived from the root */ ],
    "stats": { "original_ok": true, "variants_ok": 15, "variants_total": 15, "complete": true }
} ] }
```

`is_true_source_photo` is **true** only when the root file is (a copy of) the actual source
photograph / artwork — e.g. Antonio Guillem's stock photo, Dave Roth's Disaster Girl photo,
KC Green's full comic strip. It is **false** when the best available root is the earliest
widely used *template* (a frame grab from a film/TV episode, a crop of a paywalled stock photo,
a composite), and the note says what the true source is. Many meme "originals" are themselves
crops of older photos; the note is explicit about this for every family.

### Variant kinds used

* `caption` - the image with text added (Imgflip-generated memes, Know Your Meme gallery macros, early captioned versions).
* `crop` - a re-upload of the template that is cropped / resized / re-encoded (Imgflip blank templates, duplicate template uploads, Know Your Meme 200x200 icon crop).
* `lowres` - same picture at lower resolution or re-encoded by a hosting site (Know Your Meme `facebook`/`newsfeed` renditions, Wikipedia fair-use copies). Entries with a `parent` are *second-generation* derivatives (e.g. a KYM downscale of a captioned macro), which gives the tree depth > 1.
* `screenshot` - a screenshot of the tweet / forum / Facebook post that first spread the image (UI chrome around the picture).
* `other` - edits that are not plain crops: sign text digitally removed (Change My Mind, Boardroom Suggestion templates), subject cut out onto transparency (Bernie mittens PNGs).
* `mirror`, `color`, `sticker` - **not populated from the web.** Mirrored / colour-shifted / stickered reposts exist but are not indexed by title anywhere, so they cannot be harvested deterministically. If you need them, generate them synthetically from `original.*` (a `derive.py` step would be the natural place; it was deliberately kept out of this corpus so that every file here is a real repost with a URL).

## How it was sourced

1. **Family list.** The 30 requested families (Galaxy Brain was dropped because it is the same family as Expanding Brain and replaced by One Does Not Simply), plus 8 extra well-documented families kept as spares (Bernie Sanders Mittens, Epic Handshake, Awkward Look Monkey Puppet, Futurama Fry, Batman Slapping Robin, Sad Keanu, Kombucha Girl, Tuxedo Winnie the Pooh).
2. **Harvest (`tools/harvest.py`).** For each family: the Imgflip blank template(s) and the top user-made memes from the template gallery; the Know Your Meme entry (icon in several server renditions, the *Origin* section text and its images, the photo gallery sorted by views); and the files attached to the English Wikipedia article (only the fair-use meme copies are used, not Commons portraits of the people involved).
3. **Curation (`tools/sources.json`).** For every family the root image was chosen by hand from the harvested pool after reading the KYM origin section (and Wikipedia where an article exists): preferring an archived copy of the actual source photo when one is online, otherwise the canonical template. Source URL, date (as precise as the source allows), photographer/creator and `is_true_source_photo` were recorded. Gallery items that are *not* derivatives of the root (fan art, "where are they now" photos, tweets about the subject, parodies that re-stage the scene with a different subject) were excluded by title; same-shoot photos were kept separately as `related_not_derived` hard negatives; composite roots list their `components`.
4. **Visual QA.** Every root (and each family's variants) was rendered to a contact sheet (`tools/contact_sheet.py`) and eyeballed; mis-picks were corrected in `sources.json` and the manifest rebuilt.
5. **Download (`download.py`).** All files fetched with a browser User-Agent and verified with Pillow; dimensions, byte size and SHA-256 recorded.

## Licensing

All images are third-party copyrighted works (stock photos, film/TV frames, comics, personal
photos, user-generated macros) obtained from public URLs purely for **local, non-commercial
testing** of a provenance algorithm. They are **not redistributed**: `images/` is git-ignored
and must not be committed, published or shared. Only the manifests (URLs + metadata) are kept
in the repository. Source documentation (Know Your Meme, Wikipedia) is linked per family;
rights holders are named in `source_note` where the record identifies them (Antonio Guillem /
iStock, Dave Roth, Laney Griner, Atsuko Sato, Bryan Bundesen, KC Green, Jake Clark, Sam Smith,
John Kleckner / Hejibits, Ron Asadorian / Splash News, Brendan Smialowski / AFP-Getty, the
studios owning the film and TV frames). If you are a rights holder and object to this local
test use, delete the family from `manifest.json`.

"""

KNOWN_GAPS = """
## Known gaps and caveats

* **Paywalled true sources.** For Distracted Boyfriend, Hide the Pain Harold and First World Problems the licensed stock originals are behind iStock / Dreamstime paywalls; the corpus uses the comp-size copy archived on Know Your Meme (Distracted Boyfriend, flagged `is_true_source_photo: true` because it is the same frame at reduced size) or the watermark-removed template (Harold, FWP, flagged `false`).
* **Frame grabs, not masters.** Every film/TV/anime family (Drake, Pigeon, Pikachu, Roll Safe, Ancient Aliens, Overly Attached Girlfriend, Mocking SpongeBob, Arthur, Evil Kermit, DiCaprio, Math Lady, Chloe, Blinking Guy, One Does Not Simply, Epic Handshake, Monkey Puppet, Futurama Fry, Kombucha Girl, Tuxedo Pooh) is rooted at the widely used frame grab, so the true root (the video) is outside the corpus and the "original" is itself a lossy derivative.
* **Composites.** Woman Yelling at a Cat, Drake Hotline Bling, Expanding Brain, Monkey Puppet, Kombucha Girl and Tuxedo Pooh are two/four-panel composites; only Woman Yelling at a Cat has its two component photos archived separately (`components`). Expanding Brain's brain images are of unknown stock provenance.
* **Gallery noise.** Know Your Meme gallery picks were filtered by title, not by looking at every image; a few `caption` variants may be loose parodies (re-staged with a different base image) rather than strict derivatives. Treat `origin: "kym photo"` entries as the least certain; `imgflip template` / `imgflip meme` / `kym icon` / `wikipedia` entries are generated directly from the template and are certain.
* **No mirror / colour / sticker variants** (see *Variant kinds*). The corpus covers caption, crop/re-upload, re-encode/downscale, screenshot and cut-out edits only.
* **Second-generation depth is shallow.** Only the KYM `newsfeed` downscales (parent = a captioned macro) and the KYM `facebook`/`medium` renditions (parent = the icon) have an explicit non-root parent; all other variants are first-generation children of the root. Deeper chains (caption of a caption) exist in the wild but are not labelled here.
* **Dates** are as precise as the source allows: exact day for tweets/uploads/air dates, month or year when only that is documented (Disaster Girl photo 2005-01, Sad Keanu 2010-05, FWP 2011).
* **URL stability.** `i.kym-cdn.com` and `i.imgflip.com` URLs have been stable for years but are not permanent; `manifest.resolved.json` carries SHA-256 so a re-download can be validated.
"""


def main():
    res = json.loads((ROOT / "manifest.resolved.json").read_text(encoding="utf-8"))
    log = json.loads((ROOT / "download_log.json").read_text(encoding="utf-8"))
    s = res["summary"]
    lines = [INTRO]
    lines.append("## Status of the last download run\n")
    lines.append(f"* Families: **{s['families_total']}** ({s['families_complete']} complete = original + >= 6 variants downloaded)")
    lines.append(f"* Images on disk and verified with Pillow: **{s['images_ok']}**; failed URLs: **{s['images_failed']}** (see `download_log.json`)")
    lines.append(f"* Run: {s['run_utc']}\n")
    lines.append("## Families\n")
    lines.append("| # | Family | Root is true source photo? | Root source (date) | Variants downloaded | Kinds | Extras | Caveats |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for i, f in enumerate(res["families"], 1):
        o = f["original"]
        kinds = {}
        for v in f["variants"]:
            if v.get("downloaded"):
                kinds[v["kind"]] = kinds.get(v["kind"], 0) + 1
        kinds_s = ", ".join(f"{k} {n}" for k, n in sorted(kinds.items()))
        extras = []
        if f.get("components"):
            extras.append(f"{sum(1 for c in f['components'] if c.get('downloaded'))} components")
        if f.get("related_not_derived"):
            extras.append(f"{sum(1 for c in f['related_not_derived'] if c.get('downloaded'))} hard negatives")
        src = o["source_note"].split(". ")[0]
        if len(src) > 150:
            src = src[:150].rsplit(" ", 1)[0] + "..."

        caveat = "" if o["is_true_source_photo"] else "root is template / frame grab"
        failed = [v for v in f["variants"] if not v.get("downloaded")]
        if failed:
            caveat = (caveat + "; " if caveat else "") + f"{len(failed)} URL(s) failed"
        if not o.get("downloaded"):
            caveat = "ROOT DOWNLOAD FAILED; " + caveat
        lines.append(f"| {i} | **{f['name']}** (`{f['id']}`) | {'yes' if o['is_true_source_photo'] else 'no'} | [{src}]({o['source_url']}) ({o['date']}) | {f['stats']['variants_ok']}/{f['stats']['variants_total']} | {kinds_s} | {', '.join(extras) or '-'} | {caveat or '-'} |")
    lines.append("")
    if log["failures"]:
        lines.append("### Failed URLs in the last run\n")
        for e in log["failures"]:
            lines.append(f"* `{e['family']}` {e['file']} - {e['error']} - {e['url']}")
        lines.append("")
    lines.append(KNOWN_GAPS)
    lines.append("\n## Re-running\n\n```powershell\n.venv\\Scripts\\python.exe benchmark\\memes\\download.py            # idempotent; add --force to re-fetch\n.venv\\Scripts\\python.exe benchmark\\memes\\tools\\harvest.py benchmark\\memes\\tools\\families.json benchmark\\memes\\tools\\harvested.json   # refresh URL pool\n.venv\\Scripts\\python.exe benchmark\\memes\\tools\\build_manifest.py   # rebuild manifest.json\n.venv\\Scripts\\python.exe benchmark\\memes\\tools\\write_readme.py      # regenerate this file\n```\n")
    (ROOT / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote README.md")


if __name__ == "__main__":
    main()
